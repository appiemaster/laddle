// Generates the daily puzzle schedule:
//
//   node scripts/build-daily.ts [--start YYYY-MM-DD]
//   -> src/game/schedule.ts
//
// Already scheduled days are KEPT as long as they are still valid puzzles
// with the word list as it is now (so a list change never moves them); only
// broken days are replaced, and the schedule is extended to
// Config.daily.scheduleDays past today. --start sets day #1 for a new
// schedule (default: today); it is ignored once a schedule exists.
// Start and target words don't repeat within Config.daily.noRepeatDays.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { Config } from "../src/game/config.ts";
import { getDict } from "../src/game/dictionary.ts";
import { getGraph } from "../src/game/graph.ts";
import { fromWords, pick } from "../src/game/puzzle.ts";
import { fnv1a, seeded } from "../src/game/random.ts";

const DAY_MS = 86_400_000;
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src/game/schedule.ts");
const range = Config.daily.range;
const graph = getGraph();
const today = Math.floor(Date.now() / DAY_MS);

let firstDay = today;
const startArg = process.argv.indexOf("--start");
if (startArg >= 0) firstDay = Math.floor(Date.parse(process.argv[startArg + 1] + "T00:00:00Z") / DAY_MS);

const days: (string[] | null)[] = [];
if (existsSync(out)) {
  const text = readFileSync(out, "utf8");
  const first = text.match(/firstDay = (\d+)/);
  const packed = text.match(/pairs =\s*"([A-Z]*)"/);
  if (first && packed && packed[1].length > 0) {
    firstDay = Number(first[1]);
    for (let i = 0; i < packed[1].length; i += 8) {
      days.push([packed[1].slice(i, i + 4), packed[1].slice(i + 4, i + 8)]);
    }
  }
}

function valid(pair: string[]): boolean {
  const p = fromWords(graph, pair[0], pair[1]);
  return p !== null && p.par >= range.minPar && p.par <= range.maxPar;
}

let replaced = 0;
for (let i = 0; i < days.length; i++) {
  if (!valid(days[i]!)) {
    console.log(`day #${i + 1}: ${days[i]!.join(" -> ")} is no longer valid, replacing it`);
    days[i] = null;
    replaced++;
  }
}
const kept = days.length - replaced;
const lastDay = Math.max(firstDay + days.length - 1, today + Config.daily.scheduleDays);
while (days.length < lastDay - firstDay + 1) days.push(null);

// word -> indexes of the days it is a start or target on.
const used = new Map<string, number[]>();
const use = (word: string, i: number) => {
  const list = used.get(word);
  if (list) list.push(i);
  else used.set(word, [i]);
};
days.forEach((pair, i) => pair && pair.forEach((w) => use(w, i)));
const free = (word: string, i: number) =>
  !(used.get(word) ?? []).some((j) => Math.abs(j - i) < Config.daily.noRepeatDays);

let fallback = 0;
days.forEach((pair, i) => {
  if (pair) return;
  const day = firstDay + i;
  const rng = seeded(fnv1a(`${Config.daily.salt}-schedule-L${Config.length}-${day}`));
  let p = pick(graph, rng, range, (s, t) => free(s, i) && free(t, i), 200);
  if (!p) {
    fallback++;
    p = pick(graph, rng, range);
  }
  if (!p) throw new Error(`no puzzle for day #${i + 1}`);
  days[i] = [p.start, p.target];
  use(p.start, i);
  use(p.target, i);
});

const iso = (day: number) => new Date(day * DAY_MS).toISOString().slice(0, 10);
writeFileSync(
  out,
  `// GENERATED by scripts/build-daily.ts - do not edit by hand.
// Daily puzzles from ${iso(firstDay)} (day #1) to ${iso(lastDay)}, word list ${getDict().version}.
// Each day is 8 letters: start word then target word.
export const firstDay = ${firstDay};
export const pairs =
  "${days.map((p) => p!.join("")).join("")}";
`,
);
console.log(
  `${days.length} days (${iso(firstDay)} .. ${iso(lastDay)}): kept ${kept}, new ${days.length - kept}` +
    (fallback ? `, ${fallback} with a repeated word` : ""),
);
