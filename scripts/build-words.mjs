// Copies the screened 4-letter list from the Roblox game into the web game:
//
//   node scripts/build-words.mjs [path/to/word-ladder]   (default ../word-ladder)
//   -> src/game/words4.ts
//
// It reads only the GENERATED src/shared/Words/Len4.luau (already screened by
// tools/build_words.py there). The raw source lists never come here. To change
// the words, edit allow4/deny4/notarget4 in the Roblox repo, rebuild there,
// then run this and `npm run daily`.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(process.argv[2] ?? join(here, "..", "..", "word-ladder"));
const src = readFileSync(join(repo, "src/shared/Words/Len4.luau"), "utf8");

function field(name) {
  const m = src.match(new RegExp(`\\b${name}\\s*=\\s*"([^"]*)"`));
  if (!m) throw new Error(`Len4.luau: no ${name} field`);
  return m[1];
}

const version = field("version");
const valid = field("valid");
const common = field("common");
for (const [name, packed] of [["valid", valid], ["common", common]]) {
  if (!/^[A-Z]*$/.test(packed) || packed.length % 4 !== 0) throw new Error(`Len4.luau: bad ${name} list`);
}

const out = join(here, "..", "src/game/words4.ts");
writeFileSync(
  out,
  `// GENERATED by scripts/build-words.mjs from the Roblox game's Len4.luau - do not edit.
// Words are concatenated uppercase strings, 4 letters each.
// valid: ENABLE word list (public domain). common: 12dicts 2of12 + 6of12 by
// Alan Beale (public domain). Screened with LDNOOBW (CC BY 4.0), none of which ships.
export const version = ${JSON.stringify(version)};
export const valid = ${JSON.stringify(valid)};
export const common = ${JSON.stringify(common)};
`,
);
console.log(`${version}: ${valid.length / 4} valid, ${common.length / 4} common -> ${out}`);
